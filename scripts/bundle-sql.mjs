// Concatenates all migrations + seed into supabase/setup-all.sql so the whole
// database can be created by pasting one file into the Supabase SQL Editor.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'supabase/migrations'
const parts = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => `-- >>> ${f}\n${readFileSync(join(dir, f), 'utf8')}`)
parts.push(`-- >>> seed.sql\n${readFileSync('supabase/seed.sql', 'utf8')}`)

const header = `-- GENERATED by scripts/bundle-sql.mjs – do not edit by hand.
-- Paste into Supabase → SQL Editor → Run, on a fresh project.\n\nbegin;\n\n`
writeFileSync('supabase/setup-all.sql', header + parts.join('\n\n') + '\ncommit;\n')
console.log('Wrote supabase/setup-all.sql')
